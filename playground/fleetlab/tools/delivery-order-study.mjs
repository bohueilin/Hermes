// Reproducible compact summaries. Scientific identities include every normalized input field.
import {constants,closeSync,lstatSync,openSync,readFileSync,realpathSync,writeFileSync} from 'node:fs';
import {dirname,resolve} from 'node:path';import {fileURLToPath,pathToFileURL} from 'node:url';
import {deliveryInput,deliveryDigest} from '../src/model/software-delivery-contract.js';
import {runDelivery} from '../src/model/software-delivery.js';
import {verifyDelivery} from '../src/model/software-delivery-verify.js';
import {ORDER_INPUT_SCHEMA,ORDER_DOMAIN,ORDER_MANIFEST_SCHEMA,ORDER_POLICY_VERSION,orderDigest} from '../src/model/delivery-order-contract.js';
import {searchDeliveryOrders} from '../src/model/delivery-order-search.js';
import {verifyOrderStudy,ORDER_STUDY_VERIFIER_VERSION} from '../src/model/delivery-order-study-verify.js';
const MODULE_PATH=resolve(dirname(fileURLToPath(import.meta.url)),'../src/data/delivery-order-study.js');
const CASES=[['default','Different targets',[480,340,290,240]],['impossible','One impossible target',[220,340,290,240]],['close','Close targets',[235,280,328,480]],['tie','Equal targets',[480,480,480,480]]];
export function generateOrderStudy(){
 const cases={};
 for(const [id,name,targets]of CASES){
  const versions={};
  for(const q of [1000,250]){
   const delivery=deliveryInput('default',q);delivery.requests.forEach((r,i)=>{r.arrival_ms=i*30000;r.deadline_ms=targets[i]*1000;});
   const input={schema:ORDER_INPUT_SCHEMA,domain:ORDER_DOMAIN,delivery},s=searchDeliveryOrders(input),checked=verifyOrderStudy(s);
   if(!checked.ok)throw Error(checked.errors.join(';'));
   const equal=runDelivery(delivery,'cold'),ev=verifyDelivery(equal);if(!ev.ok)throw Error(ev.errors.join(';'));
   const best=s.records.find(r=>r.order.join()===s.representative_order.join());
   versions[q]={input,input_digest:orderDigest(input),study_digest:s.study_digest,best_orders:s.best_orders,representative_order:s.representative_order,
    best_metrics:best.metrics,fcfs_metrics:s.records[0].metrics,equal_share:{input_digest:deliveryDigest(delivery),record_digest:equal.record_digest,metrics:equal.metrics}};
  }
  cases[id]={id,name,...versions[1000],refinement:{quantum_ms:250,...versions[250]}};
 }
 return {schema:ORDER_MANIFEST_SCHEMA,policy_version:ORDER_POLICY_VERSION,verifier_version:ORDER_STUDY_VERIFIER_VERSION,cases};
}
export const orderStudyModule=m=>`// Generated by tools/delivery-order-study.mjs --write-module; do not edit by hand.\nexport const ORDER_STUDY=Object.freeze(${JSON.stringify(m)});\n`;
export function main(argv){
 try{
  if(argv.length!==1||!['--check','--write-module'].includes(argv[0]))throw Error('Use --check or --write-module.');
  if(realpathSync.native(dirname(MODULE_PATH))!==dirname(MODULE_PATH))throw Error('Linked module parent refused.');
  try{const s=lstatSync(MODULE_PATH);if(!s.isFile()||s.isSymbolicLink())throw Error('Regular module required.');}catch(e){if(e.code!=='ENOENT'||argv[0]==='--check')throw e;}
  const text=orderStudyModule(generateOrderStudy());
  if(argv[0]==='--check'){if(readFileSync(MODULE_PATH,'utf8')!==text)throw Error('Generated order study is stale.');}
  else{const fd=openSync(MODULE_PATH,constants.O_WRONLY|constants.O_CREAT|constants.O_TRUNC|constants.O_NOFOLLOW,0o644);try{writeFileSync(fd,text);}finally{closeSync(fd);}}
  console.log(`delivery-order-study: 8 complete studies (192 records) and 8 equal-share records checked; ${Buffer.byteLength(text)} bytes.`);return 0;
 }catch(e){console.error(e.message);return 1;}
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href)process.exitCode=main(process.argv.slice(2));
