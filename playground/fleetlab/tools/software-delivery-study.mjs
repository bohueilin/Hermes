// Reconstruct and independently verify all four NF04-B pairs at both declared quanta.
// Only --write-module may write, and only to the named generated data module.
import {constants,closeSync,lstatSync,openSync,readFileSync,realpathSync,writeFileSync} from 'node:fs';
import {dirname,resolve} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {DELIVERY_INPUT_SCHEMA,DELIVERY_RECORD_SCHEMA,DELIVERY_POLICY_VERSION,DELIVERY_MANIFEST_SCHEMA,
  deliveryInput,deliveryDigest,canonicalDelivery} from '../src/model/software-delivery-contract.js';
import {runDelivery} from '../src/model/software-delivery.js';
import {verifyDelivery,DELIVERY_VERIFIER_VERSION} from '../src/model/software-delivery-verify.js';

const MODULE_PATH=resolve(dirname(fileURLToPath(import.meta.url)),'../src/data/software-delivery-study.js');
const CASES=[['default','Four vehicles, one update'],['one','One vehicle'],['slow-local','Slower local link'],['two-arrivals','Two arrivals']];
const POLICIES=['repeated','cold'];
const delta=(primary,refinement)=>primary===null||refinement===null?null:refinement-primary;
export function deliveryRefinementDifferences(primary,refined){
  const p=primary.metrics,r=refined.metrics;
  return {all_ready_ms:{primary:p.all_ready_ms,refinement:r.all_ready_ms,delta_ms:delta(p.all_ready_ms,r.all_ready_ms)},
    on_time_count:{primary:p.on_time_count,refinement:r.on_time_count,delta:r.on_time_count-p.on_time_count},
    ready_ms:primary.outcomes.map(outcome=>{const next=refined.outcomes.find(o=>o.id===outcome.id).ready_ms;
      return {id:outcome.id,primary:outcome.ready_ms,refinement:next,delta_ms:delta(outcome.ready_ms,next)};}),
    metric_changes:Object.fromEntries(Object.keys(p).filter(key=>p[key]!==r[key]).map(key=>[key,{primary:p[key],refinement:r[key]}]))};
}

export function generateDeliveryStudy({verify=verifyDelivery}={}){
  const manifest={schema:DELIVERY_MANIFEST_SCHEMA,
    versions:{input:DELIVERY_INPUT_SCHEMA,record:DELIVERY_RECORD_SCHEMA,policy:DELIVERY_POLICY_VERSION,verifier:DELIVERY_VERIFIER_VERSION},cases:{}};
  for(const [id,name]of CASES){
    const input=deliveryInput(id),refinementInput=deliveryInput(id,250),runs={};
    for(const [label,common]of [['primary',input],['refinement',refinementInput]]){
      runs[label]={};
      for(const policy of POLICIES){
        const record=runDelivery(common,policy),checked=verify(record);
        if(!checked.ok)throw Error(`Study rejected ${id}/${label}/${policy}: ${checked.errors.join('; ')}`);
        if(checked.record_digest!==record.record_digest||checked.input_digest!==record.input_digest||
          canonicalDelivery(checked.metrics)!==canonicalDelivery(record.metrics))throw Error(`Study verification identity mismatch ${id}/${label}/${policy}`);
        runs[label][policy]={record,summary:{record_digest:checked.record_digest,metrics:checked.metrics}};
      }
    }
    manifest.cases[id]={id,name,input,input_digest:deliveryDigest(input),
      primary:Object.fromEntries(POLICIES.map(policy=>[policy,runs.primary[policy].summary])),
      refinement:{quantum_ms:250,input_digest:deliveryDigest(refinementInput),arms:Object.fromEntries(POLICIES.map(policy=>[policy,runs.refinement[policy].summary])),
      differences:Object.fromEntries(POLICIES.map(policy=>[policy,deliveryRefinementDifferences(runs.primary[policy].record,runs.refinement[policy].record)]))}};
  }
  return manifest;
}

export function deliveryStudyModule(manifest){
  return `// Generated by tools/software-delivery-study.mjs --write-module; do not edit by hand.\nexport const DELIVERY_STUDY=Object.freeze(${JSON.stringify(manifest)});\n`;
}
function checkExactTarget(required){
  if(realpathSync.native(dirname(MODULE_PATH))!==dirname(MODULE_PATH))throw Error('Refusing a symlink parent of the generated module.');
  try{if(!lstatSync(MODULE_PATH).isFile()||lstatSync(MODULE_PATH).isSymbolicLink())throw Error('Refusing a non-regular generated module.');}
  catch(error){if(error.code!=='ENOENT'||required)throw error;}
}

export function main(argv,{log=console.log,error=console.error}={}){
  if(argv.length!==1||!['--write-module','--check'].includes(argv[0])){
    error('Usage: software-delivery-study.mjs --write-module | --check (only the declared data module may be written).');return 2;
  }
  try{
    checkExactTarget(argv[0]==='--check');
    const text=deliveryStudyModule(generateDeliveryStudy());
    if(argv[0]==='--check'){
      if(readFileSync(MODULE_PATH,'utf8')!==text)throw Error('Generated study is stale; independently regenerate with --write-module.');
      log(`software-delivery-study: 16 checked runs match the generated module (${Buffer.byteLength(text)} bytes).`);
    }else{
      // The literal destination and O_NOFOLLOW preserve the packer writer boundary.
      const fd=openSync(MODULE_PATH,constants.O_WRONLY|constants.O_CREAT|constants.O_TRUNC|constants.O_NOFOLLOW,0o644);
      try{writeFileSync(fd,text);}finally{closeSync(fd);}
      log(`software-delivery-study: wrote 16 checked summaries (${Buffer.byteLength(text)} bytes).`);
    }
    return 0;
  }catch(e){error(`software-delivery-study: ${e.message}`);return 1;}
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href)process.exitCode=main(process.argv.slice(2));
